/* Milena · service worker — чтобы программа не качала одно и то же по плохому каналу.

   Зачем. Клиника в России, интернет там плохой, и на компьютерах постоянно
   включён VPN — то есть маршрут до сайта длинный всегда, это не лечится.
   Холодный заход весит ~800 КБ и не сжимается (хостинг Timeweb этого не умеет,
   см. docs/timeweb-caddy-request.md). После этого файла второй и все следующие
   заходы не качают НИЧЕГО тяжёлого: всё лежит у браузера. И программа
   открывается даже когда сети нет вовсе.

   ⚠ ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ: кэша ответов базы. Это программа про наличные
   деньги; показать вчерашние суммы как сегодняшние опаснее, чем не показать
   ничего. Кэшируем ТОЛЬКО свои статические файлы, всё чужое (Supabase) идёт
   мимо service worker в сеть, как и раньше.

   Две разные стратегии, и это принципиально:
   • файлы с версией в адресе (app.js?v=137) — «сначала кэш». Адрес меняется
     при каждой выкатке, значит старое никогда не подменит новое;
   • сама страница — «сначала сеть», кэш только как запасной аэродром. Иначе мы
     подрались бы с проверкой свежести в index.html, которая ходит за страницей
     с no-store и перезагружает окно, когда на сервере новее. Эта проверка —
     единственное, чем выкатки доходят до людей; ломать её нельзя.

   Аварийный выход: открыть сайт с ?nosw=1 — service worker снимется и почистит
   кэши. Он живёт НА СТОРОНЕ СТРАНИЦЫ (index.html), а не здесь, и появился тем
   же коммитом, что и регистрация: такой файл сам себя с сервера не удаляет, и
   сломанный sw лечился бы руками у каждого. */

const ВЕРСИЯ = 'milena-sw-1';

// Свои файлы, которые можно держать в кэше. config.js СОЗНАТЕЛЬНО не здесь:
// в нём адрес и ключ базы, версии в имени у него нет, и подменить его старым
// значило бы увести программу на прежний проект.
const КЭШИРУЕМ = [
  /\/app\.js(\?|$)/, /\/store\.js(\?|$)/, /\/styles\.css(\?|$)/,
  /\/vendor\/supabase\.js(\?|$)/,
  /\/favicon\.svg$/, /\/manifest\.json$/, /\/(icon|apple-touch)[\w-]*\.png$/,
];

self.addEventListener('install', e => {
  // Не ждём, пока закроются старые вкладки: обновление конфига кэша должно
  // доезжать сразу, иначе человек с открытой на весь день вкладкой не получит
  // исправление никогда.
  self.skipWaiting();
});

self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    for (const имя of await caches.keys()) if (имя !== ВЕРСИЯ) await caches.delete(имя);
    await self.clients.claim();
  })());
});

// Можно ли класть ЭТО в кэш вместо файла.
//
// ⚠ Мало проверить «ответ удался». Сервер отдаёт index.html на ЛЮБОЙ
// несуществующий путь И С КОДОМ 200 — то есть пропавший файл выглядит как
// успешно скачанный, просто внутри страница вместо кода. Положить такое в кэш
// значит подменить библиотеку страницей у конкретного человека, и надолго:
// адреса без версии он больше не перезапросит.
//
// Раньше это грозило только при первом скачивании. С фоновым обновлением ниже
// стало опаснее: оно перезаписывает УЖЕ ЛЕЖАЩЕЕ, то есть могло затереть
// исправный файл страницей — например, если человек зашёл ровно в те секунды,
// когда выкатка меняет каталог. Отсюда проверка по типу: ни один файл, который
// мы кэшируем, не является HTML, значит HTML здесь — всегда чужой.
function годится(ответ) {
  if (!ответ || !ответ.ok || ответ.type !== 'basic') return false;
  const тип = ответ.headers.get('content-type') || '';
  return !/^\s*text\/html/i.test(тип);
}

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;                       // записи — только в сеть
  let url;
  try { url = new URL(req.url); } catch (_) { return; }
  if (url.origin !== self.location.origin) return;        // база и всё чужое — мимо нас

  // Страница: сначала сеть, кэш — запасной аэродром. Свежую кладём в кэш, чтобы
  // было чем открыться без сети.
  if (req.mode === 'navigate') {
    e.respondWith((async () => {
      try {
        const ответ = await fetch(req);
        const c = await caches.open(ВЕРСИЯ);
        c.put('/', ответ.clone());
        return ответ;
      } catch (_) {
        return (await caches.match('/')) || Response.error();
      }
    })());
    return;
  }

  // Проверка свежести (index.html с ?_ts=) обязана ходить в сеть всегда.
  if (url.searchParams.has('_ts')) return;

  if (!КЭШИРУЕМ.some(re => re.test(url.pathname + url.search))) return;

  // Есть ли версия в адресе — от этого зависит, можно ли верить кэшу навсегда.
  const с_версией = url.searchParams.has('v');

  e.respondWith((async () => {
    const готовое = await caches.match(req);
    if (готовое) {
      // ⚠ Файлы БЕЗ версии в адресе (vendor/supabase.js, manifest.json,
      // favicon.svg, иконки) при честном «сначала кэш» застревали бы у
      // человека НАВСЕГДА: адрес не меняется, значит новый файл никогда не
      // спросят, а уборка ниже сносит только другие версии того же пути —
      // которых тут не бывает. Проверено на живом сайте: в кэше лежала
      // библиотека supabase.js на 200 КБ, и заменить её было нечем.
      //
      // Поэтому отдаём из кэша сразу (скорость), а свежий тянем следом и
      // молча — на будущее. Ответ этого не ждёт.
      //
      // Цена: один лишний запрос за заход на каждый такой файл. Обычный fetch
      // взят намеренно — он идёт через кэш браузера, и если тот считает файл
      // свежим, сети не будет вовсе, а если нет — уедет вопрос «не изменилось
      // ли» и вернётся пустой ответ 304. Байты при этом не качаются.
      //
      // ⚠ ТОМУ, КТО БУДЕТ МЕНЯТЬ БИБЛИОТЕКУ SUPABASE (store.js, _loadLib):
      // меняйте ИМЯ ФАЙЛА — vendor/supabase-2.js, — и здесь ничего не надо, и
      // в index.html поправьте preload. Версии в адресе у неё сознательно нет:
      // версия менялась бы на каждом выпуске и гоняла бы всем по 200 КБ на
      // ровном месте. Но из-за постоянного адреса новая библиотека доедет
      // только СО СЛЕДУЮЩЕГО захода — то есть один заход человек проведёт на
      // новом коде со старой библиотекой. Новое имя убирает это начисто.
      if (!с_версией) e.waitUntil((async () => {
        try {
          const свежий = await fetch(req);
          if (годится(свежий)) await (await caches.open(ВЕРСИЯ)).put(req, свежий);
        } catch (_) { /* нет сети — переживём, в кэше уже есть чем отвечать */ }
      })());
      return готовое;
    }
    const ответ = await fetch(req);
    // В кэш кладём только годное — см. проверку наверху: там же объяснено,
    // почему «код 200» здесь ничего не доказывает.
    if (годится(ответ)) {
      const c = await caches.open(ВЕРСИЯ);
      await c.put(req, ответ.clone());
      // И выбрасываем ПРЕЖНИЕ версии этого же файла. Адрес меняется на каждой
      // выкатке (app.js?v=150 → ?v=151), поэтому без уборки в кэше оседает
      // КАЖДАЯ версия, которую человек когда-либо открывал: app.js весит под
      // полмегабайта, выкаток бывает по десятку в день. Проверено — накапливались.
      const свежий = new URL(req.url).pathname;
      for (const старый of await c.keys()) {
        const u = new URL(старый.url);
        if (u.pathname === свежий && старый.url !== req.url) await c.delete(старый);
      }
    }
    return ответ;
  })());
});

/* Milena · service worker — чтобы программа не качала одно и то же по плохому каналу.

   Зачем. Клиника в России, интернет там плохой, и на компьютерах постоянно
   включён VPN — то есть маршрут до сайта длинный всегда, это не лечится.
   Холодный заход весит ~800 КБ и не сжимается (хостинг Timeweb этого не умеет,
   см. docs/timeweb-caddy-request.md). После этого файла второй и все следующие
   заходы не качают НИЧЕГО тяжёлого: всё лежит у браузера. И программа
   открывается даже когда сети нет вовсе.

   ⚠ ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ: кэша ответов базы. Это программа про наличные
   деньги; показать вчерашние суммы как сегодняшние опаснее, чем не показать
   ничего. Кэшируем ТОЛЬКО свои статические файлы, всё чужое (Supabase) идёт
   мимо service worker в сеть, как и раньше.

   Две разные стратегии, и это принципиально:
   • файлы с версией в адресе (app.js?v=137) — «сначала кэш». Адрес меняется
     при каждой выкатке, значит старое никогда не подменит новое;
   • сама страница — «сначала сеть», кэш только как запасной аэродром. Иначе мы
     подрались бы с проверкой свежести в index.html, которая ходит за страницей
     с no-store и перезагружает окно, когда на сервере новее. Эта проверка —
     единственное, чем выкатки доходят до людей; ломать её нельзя.

   ⚠ Файл ЕЩЁ НЕ ПОДКЛЮЧЁН: регистрации нет нигде, и это намеренно — она поедет
   вместе с выкаткой выдачи. Выключатель `?nosw=1` (снять service worker и
   почистить кэши) живёт НА СТОРОНЕ СТРАНИЦЫ, а не здесь, и должен появиться
   ТЕМ ЖЕ коммитом, что и регистрация. Подключить одно без другого нельзя: такой
   файл сам себя с сервера не удаляет, и без выключателя это ловушка. */

const ВЕРСИЯ = 'milena-sw-1';

// Свои файлы, которые можно держать в кэше. config.js СОЗНАТЕЛЬНО не здесь:
// в нём адрес и ключ базы, версии в имени у него нет, и подменить его старым
// значило бы увести программу на прежний проект.
const КЭШИРУЕМ = [
  /\/app\.js(\?|$)/, /\/store\.js(\?|$)/, /\/styles\.css(\?|$)/,
  /\/vendor\/supabase\.js(\?|$)/,
  /\/favicon\.svg$/, /\/manifest\.json$/, /\/(icon|apple-touch)[\w-]*\.png$/,
];

self.addEventListener('install', e => {
  // Не ждём, пока закроются старые вкладки: обновление конфига кэша должно
  // доезжать сразу, иначе человек с открытой на весь день вкладкой не получит
  // исправление никогда.
  self.skipWaiting();
});

self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    for (const имя of await caches.keys()) if (имя !== ВЕРСИЯ) await caches.delete(имя);
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;                       // записи — только в сеть
  let url;
  try { url = new URL(req.url); } catch (_) { return; }
  if (url.origin !== self.location.origin) return;        // база и всё чужое — мимо нас

  // Страница: сначала сеть, кэш — запасной аэродром. Свежую кладём в кэш, чтобы
  // было чем открыться без сети.
  if (req.mode === 'navigate') {
    e.respondWith((async () => {
      try {
        const ответ = await fetch(req);
        const c = await caches.open(ВЕРСИЯ);
        c.put('/', ответ.clone());
        return ответ;
      } catch (_) {
        return (await caches.match('/')) || Response.error();
      }
    })());
    return;
  }

  // Проверка свежести (index.html с ?_ts=) обязана ходить в сеть всегда.
  if (url.searchParams.has('_ts')) return;

  if (!КЭШИРУЕМ.some(re => re.test(url.pathname + url.search))) return;

  e.respondWith((async () => {
    const готовое = await caches.match(req);
    if (готовое) return готовое;
    const ответ = await fetch(req);
    // В кэш кладём только удавшееся: 404 отдаётся страницей с кодом 200
    // (особенность сервера), и закэшировать её вместо файла — надолго.
    if (ответ && ответ.ok && ответ.type === 'basic') {
      const c = await caches.open(ВЕРСИЯ);
      c.put(req, ответ.clone());
    }
    return ответ;
  })());
});
